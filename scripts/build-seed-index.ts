// Bundles data/cache/*.json into lib/seedCache.ts so the cache works on serverless without file reads.
import fs from 'fs';
import path from 'path';
const dir = path.join(__dirname, '..', 'data', 'cache');
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.json')).sort();
const entries = files.map((f) => `  ${JSON.stringify(f.replace(/\.json$/, ''))}: ${fs.readFileSync(path.join(dir, f), 'utf8').trim()},`);
fs.writeFileSync(path.join(__dirname, '..', 'lib', 'seedCache.ts'),
  `/* eslint-disable */\n// Generated by scripts/build-seed-index.ts — do not edit.\nexport interface CacheEntry { promptId: string; key: string; promptVersion: string; model: string; createdAt: string; output: any }\nexport const seedCache: Record<string, CacheEntry> = {\n${entries.join('\n')}\n};\n`);
console.log('seed entries', files.length);

// Bundle prompt files: the "## System" section of each prompts/*.md becomes the system prompt.
const pdir = path.join(__dirname, '..', 'prompts');
const prompts: Record<string, { version: string; system: string }> = {};
const preamble = fs.readFileSync(path.join(pdir, 'README.md'), 'utf8').split('Shared rules for every prompt')[1]?.split('\n').slice(1).join('\n').trim() ?? '';
for (const f of fs.readdirSync(pdir).filter((x) => x.endsWith('.md') && x !== 'README.md')) {
  const md = fs.readFileSync(path.join(pdir, f), 'utf8');
  const version = (md.match(/—\s*(v\d+)\s*—/) ?? [])[1] ?? 'v1';
  const sys = (md.split('## System')[1] ?? '').split('\n## ')[0].trim();
  const schema = (md.split('## Output schema')[1] ?? '').split('\n## ')[0].trim();
  prompts[f.replace(/\.md$/, '')] = { version, system: `${sys}\n\nShared rules:\n${preamble}\n\nReturn JSON matching this shape:\n${schema}` };
}
fs.writeFileSync(path.join(__dirname, '..', 'lib', 'promptIndex.ts'),
  `/* eslint-disable */\n// Generated from prompts/*.md by scripts/build-seed-index.ts — do not edit.\nexport const promptIndex: Record<string, { version: string; system: string }> = ${JSON.stringify(prompts, null, 1)};\n`);
console.log('prompts', Object.keys(prompts).length);
